"""Rebuild all six benchmark cases and their cohort analysis from processed inputs."""
import argparse
import csv
import hashlib
from importlib.resources import as_file, files
import json
import os
from pathlib import Path
import subprocess
import sys

UPSTREAM_COMMIT = '79e105aaf13159bee325c3ceceb6ee679e430341'
CASES = ('original_regular_mixed', 'original_regular_negative', 'original_loo_mixed',
         'original_loo_negative', 'strict_regular_mixed', 'strict_regular_negative')


def sha(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        while chunk := stream.read(1024 * 1024):
            h.update(chunk)
    return h.hexdigest()


def select_config(config, experiment, split):
    if experiment not in ('bench1', 'bench2') or not 1 <= split <= (100 if experiment == 'bench1' else 20):
        raise ValueError('bench1 splits are 1..100; bench2 splits are 1..20')
    cases = [dict(x) for x in config['cases'] if x['experiment'] == experiment and x['split'] == split]
    splits = [dict(x) for x in config['splits'] if x['experiment'] == experiment and x['split'] == split]
    stage = ('development_reused' if split <= 20 else 'frozen_evaluation') if experiment == 'bench1' else 'retrospective_second_experiment'
    if len(cases) != 6 or {x['case'] for x in cases} != set(CASES) or len(splits) != 1:
        raise ValueError('Expected exactly six distinct cases and one composition split')
    if any(x['stage'] != stage or len(x['maxima']) != 10 for x in cases) or splits[0]['stage'] != stage:
        raise ValueError('Original stage identity or ten maxima differ')
    return cases, splits


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('info', 'expression', 'variants', 'coverage', 'upstream', 'r-library', 'output'):
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--rscript', default='Rscript')
    parser.add_argument('--experiment', choices=('bench1', 'bench2'), required=True)
    parser.add_argument('--split', type=int, required=True)
    parser.add_argument('--config', type=Path, default=Path(__file__).resolve().parents[2] / 'configs/cohort_formal_portable.json')
    args = parser.parse_args()
    for path in (args.info, args.expression, args.variants, args.coverage):
        if not path.is_file():
            raise FileNotFoundError(path)
    upstream, library = args.upstream.resolve(), args.r_library.resolve()
    if not library.is_dir():
        raise FileNotFoundError(library)
    revision = subprocess.check_output(['git', '-C', str(upstream), 'rev-parse', 'HEAD'], text=True).strip()
    if revision != UPSTREAM_COMMIT:
        raise ValueError('Upstream checkout does not match the pinned MERCI commit')
    subprocess.run(['git', '-C', str(upstream), 'diff', '--quiet', 'HEAD', '--',
                    'MERCI/R/MERCI_MT_est.r', 'MERCI/R/MERCI_LOO_MT_est.r', 'MERCI/R/MERCI_ReceiverPre.r'], check=True)
    config = json.loads(args.config.read_text())
    cases, splits = select_config(config, args.experiment, args.split)
    output = args.output.resolve(); output.mkdir(parents=True, mode=0o700, exist_ok=False)
    generated = output / 'generated'; generated.mkdir(mode=0o700)
    maxima = output / 'original_maxima.csv'
    with maxima.open('x', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=['case', 'N', 'cutoff', 'maximum'], lineterminator='\n')
        writer.writeheader()
        for case in cases:
            for cutoff, value in zip(range(100, 0, -10), case['maxima']):
                writer.writerow({'case': case['case'], 'N': case['N'], 'cutoff': cutoff, 'maximum': value})
    env = os.environ.copy()
    env.update({'R_LIBS_USER': str(library), 'R_LIBS_SITE': '', 'R_LIBS': '',
                'R_PROFILE_USER': os.devnull, 'R_ENVIRON_USER': os.devnull,
                'OPENBLAS_NUM_THREADS': '1', 'OMP_NUM_THREADS': '1', 'MKL_NUM_THREADS': '1',
                'NUMEXPR_NUM_THREADS': '1', 'NUMBA_NUM_THREADS': '1'})
    here = Path(__file__).resolve().parent
    with as_file(files('merci_rank_audit').joinpath('r_helpers', 'engine.R')) as engine:
        command = [args.rscript, '--vanilla', str(here / 'score.R'),
                   *(str(x.resolve()) for x in (args.info, args.expression, args.variants, args.coverage)),
                   str(upstream), str(engine), str(here.parent / 'b1/read_coverage.R'), str(generated),
                   args.experiment, str(args.split), str(maxima), str(library)]
        subprocess.run(command, check=True, env=env)
    # Bind only newly generated bytes; historical identities remain provenance, not reusable samples.
    for case in cases:
        case['historical_score_sha256'] = case['score_sha256']
        case['source'] = str(generated / (case['case'] + '_cells.tsv.gz'))
        case['score_sha256'] = sha(Path(case['source']))
    split = splits[0]; split['historical_prepared_sha256'] = split['prepared_sha256']
    split['prepared'] = str(output / 'prepared.npz')
    null = (args.config.resolve().parent / config['null_maxima']).resolve()
    binding = {'status': 'NEW_FILES_FROM_EXPLICIT_PUBLIC_INPUTS', 'cases': cases, 'splits': splits,
               'null_maxima': str(null), 'upstream_commit': revision, 'original_config': str(args.config.resolve())}
    binding_path = output / 'binding_before_prepare.json'; binding_path.write_text(json.dumps(binding, indent=2) + '\n')
    cohort = here.parent / 'cohort'; manifest = output / 'cohort_manifest.json'
    subprocess.run([sys.executable, str(cohort / 'prepare_split.py'), '--manifest', str(binding_path),
                    '--experiment', args.experiment, '--split', str(args.split),
                    '--mixed', str(generated / 'strict_regular_mixed_cells.tsv.gz'),
                    '--negative', str(generated / 'strict_regular_negative_cells.tsv.gz'),
                    '--output', str(output / 'prepared.npz'), '--output-manifest', str(manifest)], check=True, env=env)
    subprocess.run([sys.executable, str(cohort / 'run.py'), '--manifest', str(manifest),
                    '--output', str(output / 'cohort')], check=True, env=env)
    prepared_sha = sha(output / 'prepared.npz')
    score_match = {x['case']: x['score_sha256'] == x['historical_score_sha256'] for x in cases}
    prepared_match = prepared_sha == split['historical_prepared_sha256']
    result = {'status': 'COMPLETE', 'experiment': args.experiment, 'stage': split['stage'], 'split': args.split,
              'upstream_commit': revision, 'generated_score_sha256': {x['case']: x['score_sha256'] for x in cases},
              'historical_score_sha256': {x['case']: x['historical_score_sha256'] for x in cases},
              'prepared_sha256': prepared_sha, 'historical_prepared_sha256': split['historical_prepared_sha256'],
              'historical_byte_match': {'scores': score_match, 'prepared': prepared_match},
              'historical_identity_status': ('BYTE_IDENTICAL' if all(score_match.values()) and prepared_match
                                             else 'DIFFERENT_BYTES_REQUIRES_COMPARISON'),
              'cohort_manifest_sha256': sha(manifest), 'scope': 'new files only; cell and member outputs remain private'}
    (output / 'run_complete.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result), flush=True)


if __name__ == '__main__':
    main()
